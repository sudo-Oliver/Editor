use gpui::{App, KeyBinding, actions};

actions!(
    editor,
    [
        Backspace,
        DeleteForward,
        DeleteWordLeft,
        DeleteWordRight,
        DeleteToLineStart,
        MoveLeft,
        MoveRight,
        MoveUp,
        MoveDown,
        MoveWordLeft,
        MoveWordRight,
        MoveLineStart,
        MoveLineEnd,
        MoveDocumentStart,
        MoveDocumentEnd,
        PageUp,
        PageDown,
        SelectLeft,
        SelectRight,
        SelectUp,
        SelectDown,
        SelectWordLeft,
        SelectWordRight,
        SelectLineStart,
        SelectLineEnd,
        SelectDocumentStart,
        SelectDocumentEnd,
        SelectAll,
        SelectNextOccurrence,
        AddCursorAbove,
        AddCursorBelow,
        CollapseSelections,
        Newline,
        Indent,
        AcceptCompletion,
        NextCompletion,
        PreviousCompletion,
        CloseCompletion,
        Outdent,
        Undo,
        Redo,
        Copy,
        Cut,
        Paste,
        Bold,
        Italic,
    ]
);

actions!(
    workspace,
    [
        NewFile,
        OpenFolder,
        Save,
        InsertCitation,
        LookupDoi,
        QuickFix,
        Recompile,
        CloseTab,
        GoToTab1,
        GoToTab2,
        GoToTab3,
        GoToTab4,
        GoToTab5,
        GoToTab6,
        GoToTab7,
        GoToTab8,
        GoToTab9,
        ToggleFileTree,
        TogglePreview,
        ToggleLogs,
        CloseMenu,
        OpenSettings,
        Quit,
        PdfBack,
        PdfForward,
        LayoutSplit,
        LayoutEditorOnly,
        LayoutPdfOnly,
        LayoutPdfTab,
        ToggleFocusMode,
        ToggleHub,
        OpenGitPanel,
        StartPresentation,
        ExitPresentation,
        PdfNextPage,
        PdfPreviousPage,
    ]
);

pub fn bind_keys(cx: &mut App) {
    let editor = Some("Editor");
    let pdf = Some("PdfView");
    cx.bind_keys([
        // The backdrop of an open menu holds the focus, so this does not reach the editor.
        KeyBinding::new("escape", CloseMenu, None),
        KeyBinding::new("backspace", Backspace, editor),
        KeyBinding::new("shift-backspace", Backspace, editor),
        KeyBinding::new("delete", DeleteForward, editor),
        KeyBinding::new("alt-backspace", DeleteWordLeft, editor),
        KeyBinding::new("alt-delete", DeleteWordRight, editor),
        KeyBinding::new("left", MoveLeft, editor),
        KeyBinding::new("right", MoveRight, editor),
        KeyBinding::new("up", MoveUp, editor),
        KeyBinding::new("down", MoveDown, editor),
        KeyBinding::new("home", MoveLineStart, editor),
        KeyBinding::new("end", MoveLineEnd, editor),
        KeyBinding::new("pageup", PageUp, editor),
        KeyBinding::new("pagedown", PageDown, editor),
        KeyBinding::new("shift-left", SelectLeft, editor),
        KeyBinding::new("shift-right", SelectRight, editor),
        KeyBinding::new("shift-up", SelectUp, editor),
        KeyBinding::new("shift-down", SelectDown, editor),
        KeyBinding::new("shift-home", SelectLineStart, editor),
        KeyBinding::new("shift-end", SelectLineEnd, editor),
        KeyBinding::new("alt-left", MoveWordLeft, editor),
        KeyBinding::new("alt-right", MoveWordRight, editor),
        KeyBinding::new("alt-shift-left", SelectWordLeft, editor),
        KeyBinding::new("alt-shift-right", SelectWordRight, editor),
        KeyBinding::new("secondary-a", SelectAll, editor),
        KeyBinding::new("secondary-d", SelectNextOccurrence, editor),
        KeyBinding::new("secondary-alt-up", AddCursorAbove, editor),
        KeyBinding::new("secondary-alt-down", AddCursorBelow, editor),
        KeyBinding::new("escape", CollapseSelections, editor),
        KeyBinding::new("enter", Newline, editor),
        KeyBinding::new("tab", Indent, editor),
        KeyBinding::new("shift-tab", Outdent, editor),
        // Only while the popup shows, and later than the editor keys, so they win.
        KeyBinding::new("tab", AcceptCompletion, Some("Completion")),
        KeyBinding::new("down", NextCompletion, Some("Completion")),
        KeyBinding::new("ctrl-n", NextCompletion, Some("Completion")),
        KeyBinding::new("up", PreviousCompletion, Some("Completion")),
        KeyBinding::new("ctrl-p", PreviousCompletion, Some("Completion")),
        KeyBinding::new("escape", CloseCompletion, Some("Completion")),
        KeyBinding::new("secondary-z", Undo, editor),
        KeyBinding::new("secondary-shift-z", Redo, editor),
        KeyBinding::new("secondary-y", Redo, editor),
        KeyBinding::new("secondary-c", Copy, editor),
        KeyBinding::new("secondary-x", Cut, editor),
        KeyBinding::new("secondary-v", Paste, editor),
        KeyBinding::new("secondary-b", Bold, editor),
        KeyBinding::new("secondary-i", Italic, editor),
        KeyBinding::new("secondary-c", Copy, pdf),
        KeyBinding::new("secondary-[", PdfBack, pdf),
        KeyBinding::new("secondary-]", PdfForward, pdf),
        KeyBinding::new("alt-left", PdfBack, pdf),
        KeyBinding::new("alt-right", PdfForward, pdf),
        KeyBinding::new("secondary-s", Save, None),
        KeyBinding::new("secondary-shift-c", InsertCitation, None),
        KeyBinding::new("secondary-shift-d", LookupDoi, None),
        KeyBinding::new("secondary-.", QuickFix, None),
        KeyBinding::new("secondary-enter", Recompile, None),
        KeyBinding::new("secondary-n", NewFile, None),
        KeyBinding::new("secondary-o", OpenFolder, None),
        KeyBinding::new("secondary-w", CloseTab, None),
        KeyBinding::new("secondary-1", GoToTab1, None),
        KeyBinding::new("secondary-2", GoToTab2, None),
        KeyBinding::new("secondary-3", GoToTab3, None),
        KeyBinding::new("secondary-4", GoToTab4, None),
        KeyBinding::new("secondary-5", GoToTab5, None),
        KeyBinding::new("secondary-6", GoToTab6, None),
        KeyBinding::new("secondary-7", GoToTab7, None),
        KeyBinding::new("secondary-8", GoToTab8, None),
        KeyBinding::new("secondary-9", GoToTab9, None),
        KeyBinding::new("secondary-q", Quit, None),
        KeyBinding::new("secondary-,", OpenSettings, None),
        KeyBinding::new("secondary-shift-m", ToggleFocusMode, None),
        KeyBinding::new("secondary-shift-p", ToggleHub, None),
        KeyBinding::new("secondary-shift-g", OpenGitPanel, None),
    ]);
    // The slides of a talk turn with every key a clicker or a hand reaches first.
    let presentation = Some("Presentation");
    cx.bind_keys([
        KeyBinding::new("j", PdfNextPage, presentation),
        KeyBinding::new("space", PdfNextPage, presentation),
        KeyBinding::new("down", PdfNextPage, presentation),
        KeyBinding::new("right", PdfNextPage, presentation),
        KeyBinding::new("pagedown", PdfNextPage, presentation),
        KeyBinding::new("k", PdfPreviousPage, presentation),
        KeyBinding::new("shift-space", PdfPreviousPage, presentation),
        KeyBinding::new("up", PdfPreviousPage, presentation),
        KeyBinding::new("left", PdfPreviousPage, presentation),
        KeyBinding::new("pageup", PdfPreviousPage, presentation),
        KeyBinding::new("escape", ExitPresentation, presentation),
    ]);
    #[cfg(target_os = "macos")]
    cx.bind_keys([
        KeyBinding::new("cmd-left", MoveLineStart, editor),
        KeyBinding::new("cmd-right", MoveLineEnd, editor),
        KeyBinding::new("cmd-up", MoveDocumentStart, editor),
        KeyBinding::new("cmd-down", MoveDocumentEnd, editor),
        KeyBinding::new("cmd-shift-left", SelectLineStart, editor),
        KeyBinding::new("cmd-shift-right", SelectLineEnd, editor),
        KeyBinding::new("cmd-shift-up", SelectDocumentStart, editor),
        KeyBinding::new("cmd-shift-down", SelectDocumentEnd, editor),
        KeyBinding::new("cmd-backspace", DeleteToLineStart, editor),
        KeyBinding::new("ctrl-cmd-down", LayoutSplit, None),
        KeyBinding::new("ctrl-cmd-left", LayoutEditorOnly, None),
        KeyBinding::new("ctrl-cmd-right", LayoutPdfOnly, None),
        KeyBinding::new("ctrl-cmd-up", LayoutPdfTab, None),
    ]);
    #[cfg(not(target_os = "macos"))]
    cx.bind_keys([
        KeyBinding::new("ctrl-left", MoveWordLeft, editor),
        KeyBinding::new("ctrl-right", MoveWordRight, editor),
        KeyBinding::new("ctrl-home", MoveDocumentStart, editor),
        KeyBinding::new("ctrl-end", MoveDocumentEnd, editor),
        KeyBinding::new("ctrl-shift-left", SelectWordLeft, editor),
        KeyBinding::new("ctrl-shift-right", SelectWordRight, editor),
        KeyBinding::new("ctrl-backspace", DeleteWordLeft, editor),
        KeyBinding::new("ctrl-delete", DeleteWordRight, editor),
        KeyBinding::new("ctrl-alt-down", LayoutSplit, None),
        KeyBinding::new("ctrl-alt-left", LayoutEditorOnly, None),
        KeyBinding::new("ctrl-alt-right", LayoutPdfOnly, None),
        KeyBinding::new("ctrl-alt-up", LayoutPdfTab, None),
    ]);
}
